  homepage "https://github.com/Pageking/pixel"
  url "https://github.com/Pageking/pixel/archive/refs/tags/v1.9.4.tar.gz"
  sha256 "290dccd28271a81f7b55addc5eff64b9e951df87bf48ad47e6244801762564cd"
